"""Generate static Archivo instances for the app.

The designs use Archivo's variable width axis (e.g. numbers at 68% width, weight 800).
React Native can't use variable axes reliably, so we cut exact static instances of every
width/weight pair the designs use. The same files are used on phones and in the web build
that review screenshots come from.

Usage (from frontend/, needs the variable font from
https://github.com/google/fonts/tree/main/ofl/archivo):

    uv run --with fonttools python scripts/make-fonts.py path/to/Archivo[wdth,wght].ttf

Writes assets/fonts/Archivo-<width>-<weight>.ttf and src/theme/fontFiles.ts.
Archivo is under the SIL Open Font License 1.1 (assets/fonts/OFL.txt).
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

# (width %, weight) pairs used in design/source/*.html. Add a pair here, rerun, and use
# it through `font(weight, width)` in src/theme.
INSTANCES = [
    (100, 300),
    (100, 400),
    (100, 550),
    (100, 600),
    (100, 650),
    (100, 700),
    (100, 750),
    (68, 300),  # the multiplication sign between numbers (01)
    (68, 800),  # numbers
    (72, 700),
    (72, 800),
    (75, 300),
    (80, 750),
    (85, 600),
    (85, 650),
    (85, 700),  # headings
    (92, 650),
]

# Number faces get tabular figures baked in (digits all the same width), so columns of
# numbers line up on every platform without relying on font-feature support.
TABULAR_MAX_WIDTH = 75

FRONTEND = Path(__file__).resolve().parent.parent
OUT_DIR = FRONTEND / "assets" / "fonts"
TS_FILE = FRONTEND / "src" / "theme" / "fontFiles.ts"


def family_name(width: int, weight: int) -> str:
    return f"Archivo-{width}-{weight}"


def rename(font: TTFont, name: str) -> None:
    """Give the instance its own family and PostScript name, so platforms that register
    fonts by name (iOS) never see two files claiming to be the same font."""
    table = font["name"]
    for record in list(table.names):
        if record.nameID in (16, 17, 21, 22, 25):  # typographic / WWS / variations names
            table.removeNames(nameID=record.nameID)
    for name_id, value in ((1, name), (2, "Regular"), (3, f"{name};overload"), (4, name), (6, name)):
        table.setName(value, name_id, 3, 1, 0x409)  # Windows, Unicode BMP, English
        table.setName(value, name_id, 1, 0, 0)  # Mac, Roman, English
    # Every instance is a "Regular" member of its own family.
    font["OS/2"].usWeightClass = 400
    font["OS/2"].usWidthClass = 5
    font["OS/2"].fsSelection = (font["OS/2"].fsSelection & ~0b1100001) | 0b1000000
    font["head"].macStyle = 0


def freeze_tabular_figures(font: TTFont) -> None:
    """Point the character map at the `tnum` alternates, making tabular digits the default."""
    gsub = font["GSUB"].table
    lookups = {
        index
        for record in gsub.FeatureList.FeatureRecord
        if record.FeatureTag == "tnum"
        for index in record.Feature.LookupListIndex
    }
    mapping: dict[str, str] = {}
    for index in lookups:
        for subtable in gsub.LookupList.Lookup[index].SubTable:
            if hasattr(subtable, "ExtSubTable"):
                subtable = subtable.ExtSubTable
            mapping.update(getattr(subtable, "mapping", {}))
    for table in font["cmap"].tables:
        for codepoint, glyph in list(table.cmap.items()):
            if glyph in mapping:
                table.cmap[codepoint] = mapping[glyph]


def main(variable_font: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by scripts/make-fonts.py. Do not edit.",
        "",
        "export const fontFiles = {",
    ]
    for width, weight in INSTANCES:
        name = family_name(width, weight)
        font = instantiateVariableFont(TTFont(variable_font), {"wdth": width, "wght": weight})
        rename(font, name)
        if width <= TABULAR_MAX_WIDTH:
            freeze_tabular_figures(font)
        font.recalcTimestamp = False  # same input, same bytes: reruns don't churn git
        font.save(OUT_DIR / f"{name}.ttf")
        lines.append(f"  '{name}': require('../../assets/fonts/{name}.ttf'),")
        print(f"{name}.ttf")
    lines += ["} as const;", "", "export type FontFamily = keyof typeof fontFiles;", ""]
    TS_FILE.parent.mkdir(parents=True, exist_ok=True)
    TS_FILE.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
